def translate_quest_title(title):
    translated = QUEST_TITLE_EXACT.get(title)
    if translated:
        return translated
    translated = re.sub(r": Apprentice [Ii]s Master$", ": Çırak Usta Olur", title)
    translated = re.sub(r": Six Times a Veteran$", ": Altı Kez Gazi", translated)
    translated = re.sub(r": Expert Strategy( [IVX]+)?$", r": Uzman Strateji\1", translated)
    translated = translated.replace(": Supreme Peacemaker", ": Yüce Barışçı")
    translated = translated.replace(": Supreme Antagonist", ": Yüce Hasım")
    translated = re.sub(r" Dungeon( - Stasis \d+)$", r" Zindanı\1", translated)
    return translated


def translate_pattern(source):
    """Return a reviewed Turkish rendering for recurring quest templates."""
    match = FUSE_RE.match(source)
    if match:
        return f"100 {match.group(1)} Parçasını birleştir"
    match = DEFEAT_DUNGEON_RE.match(source)
    if match:
        creature, dungeon = match.groups()
        creature = re.sub(r"^the ", "", creature, flags=re.IGNORECASE)
        return f"{dungeon} Zindanı'nda {creature} adlı düşmanı yen"
    match = DEFEAT_STASIS_RE.match(source)
    if match:
        creature, stasis = match.groups()
        creature = re.sub(r"^the ", "", creature, flags=re.IGNORECASE)
        return f"{creature} adlı düşmanı uygun seviyede ve Stasis &gt;= {stasis} iken yen"
    match = DEFEAT_STELES_RE.match(source)
    if match:
        return f"Etkin dikilitaşların tüm kombinasyonlarıyla {match.group(1)} adlı düşmanı yen"
    match = ARCHMONSTER_RE.match(source)
    if match:
        return f'"{match.group(1)}" adlı Baş Canavarı yen'
    match = COMPLETE_QUEST_RE.match(source)
    if match:
        return f'"{translate_quest_title(match.group(1))}" görevini tamamla'
    return SOURCE_EXACT.get(source)
